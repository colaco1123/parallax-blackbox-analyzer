"""Locating and running blackbox_decode, with a per-user cache of decoded CSVs."""

from __future__ import annotations

import glob
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from typing import Callable, Optional

RAW_EXTENSIONS = (".txt", ".bbl", ".bfl")
DECODER_NAME = "blackbox_decode.exe" if os.name == "nt" else "blackbox_decode"


def app_base_dir() -> str:
    """Directory holding bundled resources (PyInstaller temp dir when frozen)."""
    if getattr(sys, "frozen", False):
        return getattr(sys, "_MEIPASS", os.path.dirname(sys.executable))
    return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def find_decoder() -> Optional[str]:
    """Search the usual places for the blackbox_decode binary."""
    env = os.environ.get("BLACKBOX_DECODE")
    candidates = [env] if env else []
    base = app_base_dir()
    repo_root = os.path.dirname(base)
    candidates += [
        os.path.join(base, "bin", DECODER_NAME),
        os.path.join(base, DECODER_NAME),
        os.path.join(repo_root, "obj", DECODER_NAME),
        os.path.join(repo_root, DECODER_NAME),
    ]
    if getattr(sys, "frozen", False):
        candidates.append(os.path.join(os.path.dirname(sys.executable), DECODER_NAME))
    for c in candidates:
        if c and os.path.isfile(c):
            return c
    return shutil.which("blackbox_decode")


def user_data_dir() -> str:
    if os.name == "nt":
        root = os.environ.get("LOCALAPPDATA") or os.path.expanduser("~\\AppData\\Local")
        path = os.path.join(root, "ParallaxBlackbox")
    else:
        root = os.environ.get("XDG_CACHE_HOME") or os.path.expanduser("~/.cache")
        path = os.path.join(root, "parallax-blackbox")
    os.makedirs(path, exist_ok=True)
    return path


def cache_root() -> str:
    path = os.path.join(user_data_dir(), "decoded")
    os.makedirs(path, exist_ok=True)
    return path


def cache_key(path: str) -> str:
    st = os.stat(path)
    raw = f"{os.path.abspath(path).lower()}|{st.st_size}|{int(st.st_mtime)}|v2"
    return hashlib.sha1(raw.encode("utf-8")).hexdigest()[:16]


def cache_size_bytes() -> int:
    total = 0
    for dirpath, _, files in os.walk(cache_root()):
        for f in files:
            try:
                total += os.path.getsize(os.path.join(dirpath, f))
            except OSError:
                pass
    return total


def clear_cache() -> None:
    shutil.rmtree(cache_root(), ignore_errors=True)
    os.makedirs(cache_root(), exist_ok=True)


@dataclass
class DecodedLog:
    index: int
    csv_path: str
    duration_s: Optional[float] = None
    start_str: str = ""
    failed_frames: int = 0
    stats_text: str = ""
    event_path: Optional[str] = None


@dataclass
class DecodeResult:
    source: str
    out_dir: str
    logs: list = field(default_factory=list)
    stderr: str = ""
    from_cache: bool = False


_LOG_RE = re.compile(
    r"Log (\d+) of (\d+), start ([\d:.]+), end ([\d:.]+), duration ([\d:.]+)"
)
_FAIL_RE = re.compile(r"(\d+) frames failed to decode")


def parse_duration(text: str) -> Optional[float]:
    """Parse '01:02.345' or '00:15.338' style durations into seconds."""
    parts = text.strip().split(":")
    try:
        secs = 0.0
        for p in parts:
            secs = secs * 60 + float(p)
        return secs
    except ValueError:
        return None


def parse_decoder_output(stderr: str) -> dict:
    """Map log index -> info dict extracted from blackbox_decode's console report."""
    info: dict = {}
    current = None
    for line in stderr.splitlines():
        m = _LOG_RE.search(line)
        if m:
            current = int(m.group(1))
            info[current] = {
                "start": m.group(3),
                "duration": parse_duration(m.group(5)),
                "failed": 0,
                "stats": [],
            }
            continue
        if current is None:
            continue
        f = _FAIL_RE.search(line)
        if f:
            info[current]["failed"] = int(f.group(1))
        if line.strip() and not line.startswith("Decoding log") and "Generated by" not in line:
            info[current]["stats"].append(line.rstrip())
    return info


def sibling_csvs(csv_path: str) -> list:
    """All session CSVs that come from the same raw log as csv_path."""
    m = re.match(r"(.*)\.(\d{2,})\.csv$", csv_path, re.IGNORECASE)
    if not m:
        return [csv_path]
    found = glob.glob(glob.escape(m.group(1)) + ".*.csv")
    found = [p for p in found if re.match(r".*\.\d{2,}\.csv$", p, re.IGNORECASE)
             and not p.lower().endswith(".gps.csv")]
    return sorted(found) or [csv_path]


def _no_window_flags() -> int:
    return getattr(subprocess, "CREATE_NO_WINDOW", 0) if os.name == "nt" else 0


def decoder_version(decoder: str) -> str:
    try:
        out = subprocess.run([decoder, "--version"], capture_output=True, text=True,
                             timeout=10, creationflags=_no_window_flags())
        return (out.stdout + out.stderr).strip().splitlines()[0]
    except Exception:
        return "unknown"


def decode_log(path: str, progress: Callable[[str], None] = lambda s: None,
               use_cache: bool = True, decoder: Optional[str] = None) -> DecodeResult:
    """Decode a raw blackbox log into per-session CSVs inside the user cache."""
    decoder = decoder or find_decoder()
    if not decoder:
        raise FileNotFoundError(
            "blackbox_decode was not found. Put blackbox_decode.exe next to the app "
            "or set the BLACKBOX_DECODE environment variable.")

    out_dir = os.path.join(cache_root(), cache_key(path))
    marker = os.path.join(out_dir, "decode.json")
    base = os.path.splitext(os.path.basename(path))[0]

    if use_cache and os.path.isfile(marker):
        try:
            with open(marker, "r", encoding="utf-8") as fh:
                meta = json.load(fh)
            logs = [DecodedLog(**d) for d in meta["logs"]]
            if logs and all(os.path.isfile(l.csv_path) for l in logs):
                progress("Loaded decoded sessions from cache")
                return DecodeResult(path, out_dir, logs, meta.get("stderr", ""), True)
        except Exception:
            pass

    shutil.rmtree(out_dir, ignore_errors=True)
    os.makedirs(out_dir, exist_ok=True)
    local_copy = os.path.join(out_dir, os.path.basename(path))
    progress("Copying log to work folder...")
    shutil.copyfile(path, local_copy)

    progress("Running blackbox_decode...")
    proc = subprocess.run(
        [decoder, "--merge-gps", local_copy],
        capture_output=True, text=True, cwd=out_dir,
        creationflags=_no_window_flags(), errors="replace",
    )
    try:
        os.remove(local_copy)
    except OSError:
        pass

    stderr = (proc.stderr or "") + (proc.stdout or "")
    info = parse_decoder_output(stderr)
    csvs = sorted(p for p in glob.glob(os.path.join(glob.escape(out_dir), base + ".*.csv"))
                  if not p.lower().endswith(".gps.csv"))
    if not csvs:
        raise RuntimeError(
            f"The decoder produced no CSV files (exit code {proc.returncode}).\n\n"
            + stderr[-2000:])

    logs = []
    for csv in csvs:
        m = re.search(r"\.(\d+)\.csv$", csv)
        idx = int(m.group(1)) if m else len(logs) + 1
        meta = info.get(idx, {})
        ev = csv[:-4] + ".event"
        logs.append(DecodedLog(
            index=idx, csv_path=csv,
            duration_s=meta.get("duration"),
            start_str=meta.get("start", ""),
            failed_frames=meta.get("failed", 0),
            stats_text="\n".join(meta.get("stats", [])),
            event_path=ev if os.path.isfile(ev) else None,
        ))

    with open(marker, "w", encoding="utf-8") as fh:
        json.dump({"source": path, "stderr": stderr,
                   "logs": [l.__dict__ for l in logs]}, fh)
    progress(f"Decoded {len(logs)} session(s)")
    return DecodeResult(path, out_dir, logs, stderr, False)
