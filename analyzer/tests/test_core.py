DECODER_REPORT = """
Decoding log 'x.TXT' to 'x.02.csv'...

Log 2 of 17, start 00:46.318, end 01:18.802, duration 00:32.484

Statistics
Looptime            532 avg           34.5 std dev (6.5%)
4 frames failed to decode, rendering 5 loop iterations unreadable.

Generated by INAV blackbox_decode 9.0.0
Log 3 of 17, start 01:20.000, end 01:20.500, duration 00:00.500
"""


def test_parse_decoder_output():
    info = decoder.parse_decoder_output(DECODER_REPORT)
    assert info[2]["duration"] == pytest.approx(32.484)
    assert info[2]["failed"] == 4
    assert info[3]["duration"] == pytest.approx(0.5)
    assert "Looptime" in "\n".join(info[2]["stats"])


def test_parse_duration_minutes():
    assert decoder.parse_duration("01:02.5") == pytest.approx(62.5)


def test_minmax_keeps_spikes():
    x = np.arange(100_000, dtype=float)
    y = np.zeros_like(x)
    y[54_321] = 99.0
    y[77_777] = -42.0
    dx, dy = analysis.minmax_decimate(x, y, 1000)
    assert len(dx) <= 1001
    assert dy.max() == 99.0 and dy.min() == -42.0
    assert np.all(np.diff(dx) >= 0)


def test_minmax_handles_nan():
    x = np.arange(10_000, dtype=float)
    y = np.where(x % 3 == 0, np.nan, x)
    dx, dy = analysis.minmax_decimate(x, y, 500)
    assert np.nanmax(dy) == 9_998


def test_welch_finds_tone():
    fs = 1000.0
    t = np.arange(0, 8, 1 / fs)
    y = np.sin(2 * np.pi * 120 * t) + 0.2 * np.random.default_rng(0).normal(size=len(t))
    f, p = analysis.welch_psd(y, fs, 1024)
    peaks = analysis.dominant_peaks(f, p, 1)
    assert abs(peaks[0][0] - 120) < 2


