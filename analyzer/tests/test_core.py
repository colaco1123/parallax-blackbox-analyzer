@pytest.mark.skipif(not decoder.find_decoder() or not os.environ.get("BB_SAMPLE_LOG"),
                    reason="needs blackbox_decode and BB_SAMPLE_LOG")
def test_real_decode(tmp_path, monkeypatch):
    monkeypatch.setenv("XDG_CACHE_HOME", str(tmp_path))
    monkeypatch.setenv("LOCALAPPDATA", str(tmp_path))
    res = decoder.decode_log(os.environ["BB_SAMPLE_LOG"])
    assert res.logs and all(os.path.isfile(l.csv_path) for l in res.logs)
    again = decoder.decode_log(os.environ["BB_SAMPLE_LOG"])
    assert again.from_cache
    longest = max(res.logs, key=lambda l: l.duration_s or 0)
    headers = logdata.read_log_headers(os.environ["BB_SAMPLE_LOG"])
    assert len(headers) == len(res.logs)
    s = logdata.build_session(longest.csv_path, headers[longest.index - 1], longest.event_path)
    assert s.duration == pytest.approx(longest.duration_s, abs=0.05)
