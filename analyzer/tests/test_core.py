def test_sibling_csvs(tmp_path):
    for i in (1, 2, 10):
        (tmp_path / f"blackbox_log_x.{i:02d}.csv").write_text("a\n1\n")
    (tmp_path / "blackbox_log_x.01.gps.csv").write_text("a\n1\n")
    sibs = decoder.sibling_csvs(str(tmp_path / "blackbox_log_x.02.csv"))
    assert [os.path.basename(p) for p in sibs] == ["blackbox_log_x.01.csv", "blackbox_log_x.02.csv",
                                                   "blackbox_log_x.10.csv"]


