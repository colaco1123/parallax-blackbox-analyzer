def test_log_datetime_rejects_unset_clock():
    assert logdata.parse_log_datetime({"Log start datetime": "2041-06-28T01:04:00.000+00:00"}) is None
    assert logdata.parse_log_datetime({"Log start datetime": "0000-01-01T00:00:00.000+00:00"}) is None
    dt = logdata.parse_log_datetime({"Log start datetime": "2026-06-17T13:43:45.000+00:00"})
    assert dt.hour == 13


def test_read_headers_per_log(tmp_path):
    raw = (b"H Product:Blackbox flight data recorder by Nicholas Sherlock\n"
           b"H Firmware revision:INAV 9.0.1\nH rollPID:40,30,23,60\nI\x01\x02\x03\n"
           b"H Product:Blackbox flight data recorder by Nicholas Sherlock\n"
           b"H rollPID:50,30,23,60\nI\x00")
    p = tmp_path / "log.TXT"
    p.write_bytes(raw)
    hs = logdata.read_log_headers(str(p))
    assert len(hs) == 2
    assert hs[0]["rollPID"] == "40,30,23,60"
    assert hs[1]["rollPID"] == "50,30,23,60"
    rows = dict(logdata.summarize_headers(hs[0]))
    assert "P=40" in rows["Roll PID"]


def _write_inav_csv(path, n=2000):
    t = 1_000_000 + np.arange(n) * 1000
    df = pd.DataFrame({
        "loopIteration": np.arange(n),
        "time (us)": t,
        "rcData[3]": 1500,
        "motor[0]": 1400 + (np.arange(n) % 50),
        "surfaceRaw": np.where(np.arange(n) % 10 == 0, -1, 120),
        "gyroADC[0]": np.sin(np.arange(n) / 5.0) * 10,
        "flightModeFlags (flags)": ["0"] * 100 + ["ARM"] * (n - 200) + ["0"] * 100,
        "failsafePhase (flags)": "IDLE",
    })
    df.to_csv(path, index=False)


def test_build_session_inav(tmp_path):
    csv = tmp_path / "blackbox_log_2026-06-17_134345.02.csv"
    _write_inav_csv(csv)
    ev = tmp_path / "blackbox_log_2026-06-17_134345.02.event"
    ev.write_text(json.dumps({"name": "Sync beep", "time": 1_500_000}) + "\n"
                  + json.dumps({"name": "Sync beep", "time": 1_500_000}) + "\n")
    s = logdata.build_session(str(csv), {}, str(ev))
    assert s.kind == "inav"
    assert s.duration == pytest.approx(1.999)
    assert s.sample_rate == pytest.approx(1000, rel=0.01)
    assert s.armed_time() == pytest.approx(1.799, abs=0.01)
    assert s.events == [(0.5, "Sync beep")]
    assert "motor[0]" in s.numeric_columns and "time (us)" not in s.numeric_columns
    panels = resolve_panels(PRESET_BY_KEY["overview"], s.df.columns)
    assert [len(p.series) for p in panels] == [1, 1, 1]
    keys = [p.key for p in available_presets(s.df.columns)]
    assert "overview" in keys and "custom" in keys and "battery" not in keys


